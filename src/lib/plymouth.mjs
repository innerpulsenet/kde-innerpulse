// The boot screen: a Plymouth theme, shown from the moment the kernel has a display until the login screen, and
// again on the way down. It is the session splash's picture, so start-up reads as one screen: the carbon ground,
// the plate a little above the middle, the wordmark under it and a line at the foot.
//
// The plate never moves. Its slots open once, then a pulse of light passes through them at the working tempo. A
// Plymouth script can only place, fade and swap bitmaps, so the opening is a run of rendered plates (FRAMES of
// them, the last one the plate at rest) and the light is six lamp bitmaps, one per slot, whose opacity the script
// drives with the same sin² bump as AmbientMark.qml.
//
// The line at the foot says only what Plymouth knows: which way the machine is going, and whatever message the
// system sends (a disk check, a prompt). There is no progress bar and no timer: Plymouth's progress is a guess
// from the last boot's duration, and a figure nobody measured does not go on the screen.
//
// Sizes follow the screen: one grid unit is 1/60 of the shorter side (18 px at 1080p, the splash's own), kept
// between 12 and 36. Bitmaps ship at two sizes, for a 162 px and a 324 px plate, and the script scales from the
// nearer one above.

import { MARK, PLATE, PULSE, TEMPO, LAMP, barHeights, plateD, slotRects } from './mark.mjs';
import { hexRGB } from './palette.mjs';
import { SPLASH } from './preview.mjs';

export const PLYMOUTH = {
  id: 'innerpulse',
  name: 'innerpulse',
  dir: '/usr/share/plymouth/themes/innerpulse',
  frames: 26, // rendered plates in the opening, the last at rest: one every 40 ms
  sizes: [['1x', 162], ['2x', 324]], // [file prefix, plate px]
  entry: { w: 15.5, h: 2 }, // the password field, in grid units
  bullet: 0.45,
  wordmarkH: 2.2, // grid units, as on the splash
  wordmarkRatio: 790 / 120,
};

const f = (v) => +v.toFixed(3);
const svg = (vb, w, h, body) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" width="${w}" height="${h}">${body}</svg>\n`;

/** The opening at `o` seconds: each slot's half-height, as AmbientMark.qml's slotH. */
function openHeights(o) {
  return barHeights().map((h, i) => {
    const u = Math.min(1, Math.max(0, (o - i * PULSE.drawLag) / PULSE.drawIn));
    return MARK.minBar + (h - MARK.minBar) * (1 - (1 - u) ** 3);
  });
}

/**
 * The theme's drawings as SVG, to be rendered by the build: [{ name, svg, w, h }]. Plates and lamps share one
 * square canvas per size, so the script places them all at the same point.
 */
export function plymouthArt(t) {
  const out = [], P = PLYMOUTH, half = PLATE.size / 2, vb = `${-half} ${-half} ${PLATE.size} ${PLATE.size}`;
  const openEnd = PULSE.drawIn + MARK.beat * PULSE.drawLag;
  for (const [tag, px] of P.sizes) {
    for (let k = 0; k < P.frames; k++) {
      const heights = openHeights((k / (P.frames - 1)) * openEnd);
      out.push({ name: `${tag}-plate-${k}.png`, w: px, h: px,
        svg: svg(vb, px, px, `<path fill="${t.mark}" fill-rule="evenodd" d="${plateD({ heights })}"/>`) });
    }
    slotRects().forEach((s, i) => out.push({ name: `${tag}-lamp-${i}.png`, w: px, h: px,
      svg: svg(vb, px, px, `<rect x="${f(s.x)}" y="${f(s.y)}" width="${f(s.w)}" height="${f(s.h)}" rx="${f(s.rx)}" fill="${LAMP}"/>`) }));
  }
  // the password field and its bullet, drawn for a 36 px grid unit and scaled down by the script
  const G = 36, ew = P.entry.w * G, eh = P.entry.h * G, r = 8, b = Math.round(P.bullet * G);
  out.push({ name: 'entry.png', w: ew, h: eh,
    svg: svg(`0 0 ${ew} ${eh}`, ew, eh,
      `<rect x="1" y="1" width="${ew - 2}" height="${eh - 2}" rx="${r}" fill="${t.s1}" stroke="${t.focus}" stroke-width="2"/>`) });
  out.push({ name: 'bullet.png', w: b, h: b,
    svg: svg(`0 0 ${b} ${b}`, b, b, `<rect width="${b}" height="${b}" rx="3" fill="${t.text}"/>`) });
  return out;
}

/** The theme's descriptor. */
export const plymouthDescriptor = () => `[Plymouth Theme]
Name=${PLYMOUTH.name}
Description=The plate on carbon: its slots open once, then a pulse of light passes through them
ModuleName=script

[script]
ImageDir=${PLYMOUTH.dir}
ScriptFile=${PLYMOUTH.dir}/${PLYMOUTH.id}.script
`;

/** The theme's script, with the brand's values filled in. */
export function plymouthScript(t, version) {
  const P = PLYMOUTH, c = (hex) => hexRGB(hex).map((v) => f(v / 255)).join(', ');
  const openEnd = PULSE.drawIn + MARK.beat * PULSE.drawLag;
  return `# innerpulse boot screen ${version}. Generated by src/lib/plymouth.mjs: edit that, not this file.
#
# The carbon ground, the plate a little above the middle, the wordmark under it, a line at the foot. The plate
# never moves: its slots open once, then a pulse of light passes through them every ${TEMPO.working} s.

Window.SetBackgroundTopColor(${c(t.ground)});
Window.SetBackgroundBottomColor(${c(t.ground)});

W = Window.GetWidth();
H = Window.GetHeight();
X0 = Window.GetX();
Y0 = Window.GetY();

# one grid unit: 18 px at 1080p
gu = Math.Min(W, H) / 60;
if (gu < 12) gu = 12;
if (gu > 36) gu = 36;

size = Math.Int(${SPLASH.plate} * gu + 0.5);
if (size > Math.Min(W, H) * 0.4) size = Math.Int(Math.Min(W, H) * 0.4);
set = "2x";
native = ${P.sizes[1][1]};
if (size <= ${P.sizes[0][1]}) {
    set = "1x";
    native = ${P.sizes[0][1]};
}

fun Art(name) {
    local.image = Image(set + "-" + name + ".png");
    if (size != native) image = image.Scale(size, size);
    return image;
}

FRAMES = ${P.frames};
SLOTS = ${MARK.beat + 1};
OPEN_END = ${f(openEnd)};
PERIOD = ${TEMPO.working};
PULSE_W = ${PULSE.width};
LAG = ${PULSE.lag};
FADE = 0.4;

for (i = 0; i < FRAMES; i++) frames[i] = Art("plate-" + i);

plate_x = X0 + Math.Int((W - size) / 2);
plate_y = Y0 + Math.Int(H / 2 - ${SPLASH.lift} * gu - size / 2);

plate = Sprite(frames[0]);
plate.SetPosition(plate_x, plate_y, 10);
plate.SetOpacity(0);
shown = 0;

for (i = 0; i < SLOTS; i++) {
    lamps[i] = Sprite(Art("lamp-" + i));
    lamps[i].SetPosition(plate_x, plate_y, 11);
    lamps[i].SetOpacity(0);
}

# the wordmark, a quarter of the plate plus a grid unit under it
word_h = Math.Int(${P.wordmarkH} * gu + 0.5);
word_w = Math.Int(word_h * ${f(P.wordmarkRatio)} + 0.5);
word_y = plate_y + size + Math.Int(size / 4 + gu);
word = Sprite(Image("wordmark.png").Scale(word_w, word_h));
word.SetPosition(X0 + Math.Int((W - word_w) / 2), word_y, 10);
word.SetOpacity(0);

# ---------------------------------------------------------------- text

FONT = "JetBrains Mono, Hack, monospace " + Math.Int(gu * 0.56 + 0.5);
FONT_MEDIUM = "JetBrains Mono, Hack, monospace Medium " + Math.Int(gu * 0.56 + 0.5);

# A line of text as an image. A label drawn far larger than asked (a renderer applying its own screen scale) is
# brought back to a grid unit.
fun Line(text, red, green, blue, font) {
    local.image = Image.Text(text, red, green, blue, 1, font);
    if (image.GetHeight() > gu * 1.8) {
        image = image.Scale(Math.Int(image.GetWidth() * gu / image.GetHeight()), Math.Int(gu));
    }
    return image;
}

fun Center(sprite, image, y, z) {
    sprite.SetImage(image);
    sprite.SetPosition(X0 + Math.Int((W - image.GetWidth()) / 2), Math.Int(y), z);
}

# the rest of a string after a prefix, or NULL when it does not start with it
fun After(text, prefix) {
    local.i = 0;
    while (String(prefix).CharAt(i)) {
        if (String(prefix).CharAt(i) != String(text).CharAt(i)) return NULL;
        i++;
    }
    local.rest = "";
    while (String(text).CharAt(i)) {
        rest += String(text).CharAt(i);
        i++;
    }
    return rest;
}

foot_y = Y0 + H - 3 * gu - gu;
note_y = foot_y - 1.8 * gu;

# The line at the foot: which way the machine is going. Nothing is shown for a mode this theme has no words for.
mode = Plymouth.GetMode();
doing = "";
if (mode == "boot") doing = "Starting up…";
if (mode == "shutdown") doing = "Shutting down…";
if (mode == "reboot") doing = "Restarting…";
if (mode == "updates") doing = "Installing updates…";
if (mode == "system-upgrade") doing = "Upgrading the system…";
if (mode == "firmware-upgrade") doing = "Updating firmware…";

foot = Sprite();
if (doing != "") Center(foot, Line(doing, ${c(t.text)}, FONT_MEDIUM), foot_y, 20);
foot.SetOpacity(0);

# what the system says: a message, or a disk check's own line
note = Sprite();
note.SetOpacity(0);
note_on = 0;

fun ShowNote(text) {
    if (!text || text == "") {
        note.SetOpacity(0);
        global.note_on = 0;
        return;
    }
    Center(note, Line(text, ${c(t.text3)}, FONT), note_y, 20);
    note.SetOpacity(1);
    global.note_on = 1;
}

fun message_callback(text) {
    local.rest = After(text, "keys:");
    if (rest != NULL) text = rest;
    rest = After(text, "fsckd-cancel-msg:");
    if (rest != NULL) text = rest;
    ShowNote(text);
}
Plymouth.SetMessageFunction(message_callback);

fun hide_message_callback(text) {
    ShowNote("");
}
Plymouth.SetHideMessageFunction(hide_message_callback);

# systemd-fsckd reports "fsckd:<devices>:<progress>:<its own line>"; the line is shown as sent
fun update_status_callback(status) {
    local.rest = After(status, "fsckd:");
    if (rest == NULL) return;
    local.part = 0;
    local.devices = "";
    local.line = "";
    for (i = 0; String(rest).CharAt(i); i++) {
        local.ch = String(rest).CharAt(i);
        if (ch == ":" && part < 2) part++;
        else if (part == 0) devices += ch;
        else if (part == 2) line += ch;
    }
    if (devices == "0") line = "";
    ShowNote(line);
}
Plymouth.SetUpdateStatusFunction(update_status_callback);

# ---------------------------------------------------------------- the prompt (a disk's passphrase, a question)

ask_y = word_y + word_h + 2 * gu;
entry_w = Math.Int(${P.entry.w} * gu);
entry_h = Math.Int(${P.entry.h} * gu);
entry_image = Image("entry.png").Scale(entry_w, entry_h);
bullet_size = Math.Int(${P.bullet} * gu + 0.5);
bullet_image = Image("bullet.png").Scale(bullet_size, bullet_size);
bullet_step = bullet_size * 2;

ask = Sprite();
ask.SetOpacity(0);
entry = Sprite(entry_image);
entry_x = X0 + Math.Int((W - entry_w) / 2);
entry_y = Math.Int(ask_y + 1.6 * gu);
entry.SetPosition(entry_x, entry_y, 20);
entry.SetOpacity(0);
answer = Sprite();
answer.SetOpacity(0);
bullet_count = 0;

fun HideBullets() {
    for (i = 0; i < bullet_count; i++) bullets[i].SetOpacity(0);
}

fun ShowPrompt(text) {
    if (!text || text == "") text = "Passphrase";
    Center(ask, Line(text, ${c(t.text)}, FONT_MEDIUM), ask_y, 20);
    ask.SetOpacity(1);
    entry.SetOpacity(1);
}

fun display_password_callback(prompt, count) {
    ShowPrompt(prompt);
    answer.SetOpacity(0);
    local.room = Math.Int((entry_w - 2 * bullet_step) / bullet_step);
    if (count > room) count = room;
    for (i = 0; i < count; i++) {
        if (i >= bullet_count) {
            bullets[i] = Sprite(bullet_image);
            bullets[i].SetPosition(entry_x + bullet_step + i * bullet_step, entry_y + Math.Int((entry_h - bullet_size) / 2), 21);
            global.bullet_count = i + 1;
        }
        bullets[i].SetOpacity(1);
    }
    for (i = count; i < bullet_count; i++) bullets[i].SetOpacity(0);
}
Plymouth.SetDisplayPasswordFunction(display_password_callback);

fun display_question_callback(prompt, typed) {
    ShowPrompt(prompt);
    HideBullets();
    if (typed && typed != "") {
        local.image = Line(typed, ${c(t.text)}, FONT);
        answer.SetImage(image);
        answer.SetPosition(entry_x + bullet_step, entry_y + Math.Int((entry_h - image.GetHeight()) / 2), 21);
        answer.SetOpacity(1);
    } else {
        answer.SetOpacity(0);
    }
}
Plymouth.SetDisplayQuestionFunction(display_question_callback);

fun display_normal_callback() {
    ask.SetOpacity(0);
    entry.SetOpacity(0);
    answer.SetOpacity(0);
    HideBullets();
}
Plymouth.SetDisplayNormalFunction(display_normal_callback);

# ---------------------------------------------------------------- motion, 50 times a second

tick = 0;

fun refresh_callback() {
    global.tick++;
    local.t = tick / 50;

    # the screen fades in, easing out
    if (t <= FADE + 0.05) {
        local.a = t / FADE;
        if (a > 1) a = 1;
        local.o = 1 - (1 - a) * (1 - a) * (1 - a);
        plate.SetOpacity(o);
        word.SetOpacity(o);
        foot.SetOpacity(o);
    }

    # the slots open once
    if (shown < FRAMES - 1) {
        local.k = Math.Int(t / OPEN_END * (FRAMES - 1));
        if (k > FRAMES - 1) k = FRAMES - 1;
        if (k != shown) {
            plate.SetImage(frames[k]);
            global.shown = k;
        }
    }

    # one pulse of light per period, the first a full period after the plate appears
    local.p = t - Math.Int(t / PERIOD) * PERIOD;
    for (i = 0; i < SLOTS; i++) {
        local.lit = 0;
        if (t >= PERIOD) {
            local.u = (p - i * LAG * PERIOD) / (PULSE_W * PERIOD);
            if (u > 0 && u < 1) {
                local.s = Math.Sin(Math.Pi * u);
                lit = s * s;
            }
        }
        lamps[i].SetOpacity(lit);
    }
}
Plymouth.SetRefreshFunction(refresh_callback);
`;
}
